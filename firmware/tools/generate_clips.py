async def synthesize(text: str, voice: str, rate: str, mp3_path: Path) -> None:
    # The edge-tts service occasionally drops a request ("No audio received").
    for attempt in range(4):
        try:
            await edge_tts.Communicate(text, voice, rate=rate).save(str(mp3_path))
            return
        except Exception:
            if attempt == 3:
                raise
            await asyncio.sleep(2 * (attempt + 1))


def mp3_to_pcm_u8(mp3_path: Path, trailing_ms: int) -> bytes:
    """Decode, trim leading/trailing silence, peak-normalise, convert to u8."""
    trim = "silenceremove=start_periods=1:start_threshold=-45dB"
    raw = subprocess.run(
        [
            imageio_ffmpeg.get_ffmpeg_exe(), "-v", "error", "-i", str(mp3_path),
            "-af", f"{trim},areverse,{trim},areverse",
            "-ac", "1", "-ar", str(SAMPLE_RATE), "-f", "s16le", "-",
        ],
        check=True,
        capture_output=True,
    ).stdout
    samples = array("h", raw)
    peak = max((abs(s) for s in samples), default=0) or 1
    gain = 0.95 * 127 / peak  # 16-bit -> ±127 around the 128 midpoint
    pcm = bytes(max(0, min(255, 128 + round(s * gain))) for s in samples)
    return pcm + bytes([128]) * (SAMPLE_RATE * trailing_ms // 1000)


def write_sources(clips: list[tuple[str, str, bytes]], voice: str) -> None:
    header = [
        "// Generated by firmware/tools/generate_clips.py — do not edit.",
        f"// Voice: {voice}, {SAMPLE_RATE} Hz, 8-bit unsigned mono PCM.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"constexpr uint32_t CLIP_SAMPLE_RATE = {SAMPLE_RATE};",
        "",
        "enum ClipId : uint16_t {",
        *[f"  CLIP_{name},  // {text}" for name, text, _ in clips],
        "  CLIP_COUNT",
        "};",
        "",
        "struct ClipData {",
        "  const uint8_t* data;",
        "  uint32_t length;",
        "};",
        "",
        "extern const ClipData CLIP_TABLE[CLIP_COUNT];",
        "",
    ]
    body = ['// Generated by firmware/tools/generate_clips.py — do not edit.', '#include "clips.h"', ""]
    for name, text, pcm in clips:
        body.append(f"// {text}")
        body.append(f"static const uint8_t DATA_{name}[{len(pcm)}] = {{")
        for i in range(0, len(pcm), 32):
            body.append("  " + ",".join(str(b) for b in pcm[i : i + 32]) + ",")
        body.append("};")
    body.append("")
    body.append("const ClipData CLIP_TABLE[CLIP_COUNT] = {")
    body += [f"  {{DATA_{name}, sizeof(DATA_{name})}}," for name, _, _ in clips]
    body.append("};")
    body.append("")

    (OUT_DIR / "clips.h").write_text("\n".join(header), encoding="utf-8")
    (OUT_DIR / "clips.cpp").write_text("\n".join(body), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--voice", default="hi-IN-SwaraNeural", help="or hi-IN-MadhurNeural (male)")
    parser.add_argument("--rate", default="+5%", help="speaking rate, e.g. +10%%")
    args = parser.parse_args()

    results = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, text, trailing_ms in CLIPS:
            mp3 = Path(tmp) / f"{name}.mp3"
            asyncio.run(synthesize(text, args.voice, args.rate, mp3))
            pcm = mp3_to_pcm_u8(mp3, trailing_ms)
            results.append((name, text, pcm))
            print(f"{name:16} {len(pcm) / SAMPLE_RATE:5.2f}s  {text}")

    write_sources(results, args.voice)
    total = sum(len(p) for _, _, p in results)
    print(f"\n{len(results)} clips, {total / 1024:.0f} KB, {total / SAMPLE_RATE:.0f}s of audio -> {OUT_DIR}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
