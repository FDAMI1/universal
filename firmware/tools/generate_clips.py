"""Generates the Hindi voice clips and bakes them into the firmware.

Writes firmware/universal-speaker/clips.h and clips.cpp: 8-bit unsigned mono
PCM at 16 kHz, the format the ESP32 internal DAC plays directly. Clips live in
flash, so the firmware is a single upload (no filesystem step).

Setup (once):  pip install edge-tts imageio-ffmpeg
Run:           python firmware/tools/generate_clips.py [--voice hi-IN-MadhurNeural]
"""

import argparse
import asyncio
import subprocess
import sys
import tempfile
from array import array
from pathlib import Path

import edge_tts
import imageio_ffmpeg

SAMPLE_RATE = 16000
OUT_DIR = Path(__file__).resolve().parent.parent / "universal-speaker"

# 1–99 in Hindi are all irregular, so each gets its own clip. Order matters:
